"""p50/p95/p99 latency per stage, run via `make bench`.

PRD §9: numbers in the README must be generated by this script, not asserted.
PRD §5.4 thermal note: report CPU-only numbers from a cool machine as the
headline figures; GPU numbers are informative but not the reported default.
"""

from __future__ import annotations

import argparse
import time
from pathlib import Path

import numpy as np

FIXTURE = Path(__file__).parent.parent / "tests" / "fixtures" / "probe_sample.jpg"


def percentiles(samples_ms: list[float]) -> dict[str, float]:
    arr = np.array(samples_ms)
    return {"p50": float(np.percentile(arr, 50)), "p95": float(np.percentile(arr, 95)), "p99": float(np.percentile(arr, 99))}


def bench_stage1(n: int = 200) -> None:
    from faceanchor.vision import align, detect, embed, phash, quality
    from faceanchor.vision.decode import decode_jpeg_bytes

    raw = FIXTURE.read_bytes()

    # warmup — pays model load + session pre-warm cost once, outside the timed loop
    img = decode_jpeg_bytes(raw)
    faces = detect.detect_faces(img)
    face, err = quality.check_single_face(faces, face_index=None)
    if err:
        raise SystemExit(f"fixture unusable for bench: {err}")
    crop = align.align_and_crop(img, face)
    embed.embed_one(crop)

    stages: dict[str, list[float]] = {"decode": [], "detect": [], "align": [], "embed_probe": [], "phash": [], "total": []}

    for _ in range(n):
        t0 = time.perf_counter()
        img = decode_jpeg_bytes(raw)
        t1 = time.perf_counter()
        faces = detect.detect_faces(img)
        t2 = time.perf_counter()
        face, _ = quality.check_single_face(faces, face_index=None)
        crop = align.align_and_crop(img, face)
        t3 = time.perf_counter()
        embed.embed_one(crop)
        t4 = time.perf_counter()
        phash.phash(img)
        t5 = time.perf_counter()

        stages["decode"].append((t1 - t0) * 1000)
        stages["detect"].append((t2 - t1) * 1000)
        stages["align"].append((t3 - t2) * 1000)
        stages["embed_probe"].append((t4 - t3) * 1000)
        stages["phash"].append((t5 - t4) * 1000)
        stages["total"].append((t5 - t0) * 1000)

    print(f"Stage 1 bench, n={n}, fixture={FIXTURE.name}")
    print(f"{'stage':<14}{'p50':>8}{'p95':>8}{'p99':>8}   (ms)")
    for name, samples in stages.items():
        p = percentiles(samples)
        print(f"{name:<14}{p['p50']:>8.2f}{p['p95']:>8.2f}{p['p99']:>8.2f}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--stage", choices=["1"], default="1")
    parser.add_argument("-n", type=int, default=200)
    args = parser.parse_args()
    if args.stage == "1":
        bench_stage1(args.n)
